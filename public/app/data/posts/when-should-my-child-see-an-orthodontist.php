<h2>Early treatment vs. waiting</h2>
<p>When early treatment is recommended, it's usually called <strong>Phase 1</strong>. It's aimed at a specific issue rather than straightening every tooth. Common examples include:</p>
<ul>
  <li><strong>Palatal expanders</strong> that widen a narrow upper jaw and correct crossbites</li>
  <li><strong>Space maintainers</strong> that hold room for adult teeth after a baby tooth is lost early</li>
  <li><strong>Habit appliances</strong> that help children stop thumb sucking or tongue thrusting</li>
</ul>
