<p>Getting braces is exciting &mdash; and it comes with a few new habits. Looking after your teeth and brackets keeps treatment on schedule, protects your enamel and means a healthier, brighter smile on the day your braces come off.</p>

<h2>Brushing with braces</h2>
<p>Food gets caught around brackets and wires far more easily than on bare teeth, so brushing matters more than ever.</p>
<ul>
  <li><strong>Brush after every meal</strong> when you can, and always before bed.</li>
  <li>Use a <strong>soft-bristled brush</strong> and a fluoride toothpaste.</li>
  <li>Angle the brush down from above the brackets, then up from below, so you clean both sides of the wire.</li>
  <li>Spend about two minutes, and check in a mirror that no food is left behind.</li>
</ul>
<p>A small interdental brush (sometimes called a proxy brush) is great for reaching under the wire and between brackets.</p>

<h2>Flossing made easier</h2>
<p>Flossing with braces takes a little longer at first, but it quickly becomes routine.</p>
<ul>
  <li><strong>Floss threaders</strong> help you guide regular floss under the archwire.</li>
  <li><strong>Orthodontic floss</strong> has a stiff end that slides under the wire without a threader.</li>
  <li><strong>Water flossers</strong> are a helpful extra for flushing out food, but they work best alongside regular floss rather than instead of it.</li>
</ul>

