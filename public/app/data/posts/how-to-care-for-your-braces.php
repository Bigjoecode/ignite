<h2>Handling soreness</h2>
<p>It's normal for teeth to feel tender for a few days after braces go on and after adjustments.</p>
<ul>
  <li>Stick to soft foods like pasta, yogurt, eggs, soup and smoothies for a day or two.</li>
  <li>Press a small piece of <strong>orthodontic wax</strong> over any bracket that rubs your cheek or lip.</li>
  <li>Rinsing with warm salt water can soothe irritated spots.</li>
  <li>An over-the-counter pain reliever can help &mdash; follow the label directions.</li>
</ul>

<h2>If a bracket or wire comes loose</h2>
<p>Minor problems happen and are rarely an emergency. If a bracket loosens or a wire starts to poke, cover the sharp spot with orthodontic wax and call your Ignite Orthodontics office. Don't try to cut or bend wires yourself &mdash; we'll fix it properly and keep your treatment on track.</p>

<h2>Sports and activities</h2>
<p>You can keep playing sports and musical instruments with braces. For contact sports, wear an orthodontic mouthguard to protect your teeth, lips and cheeks.</p>

<h2>Keep up with appointments</h2>
<p>Regular adjustment visits, usually every four to eight weeks, keep your teeth moving as planned. Keep seeing your general dentist for cleanings during treatment too.</p>
