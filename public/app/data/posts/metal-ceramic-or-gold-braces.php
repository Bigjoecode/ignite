<h2>Ceramic braces</h2>
<p>Ceramic braces work just like metal braces, but the brackets are made from a tooth-colored or clear material that blends in with your smile.</p>
<ul>
  <li><strong>Discreet:</strong> much less noticeable in photos and conversation.</li>
  <li><strong>A little more delicate:</strong> ceramic is more brittle than steel, so brackets can chip if you bite something hard.</li>
  <li><strong>Mind the elastics:</strong> clear ties can pick up stains from coffee, tea, curry or tomato sauce between visits, so many patients choose a light or tooth-colored option.</li>
</ul>

<h2>Gold braces</h2>
<p>Gold braces have the same strength and function as traditional braces, finished with a polished gold color. They're a style choice for patients who want their braces to stand out rather than blend in.</p>
<ul>
  <li><strong>Distinctive look:</strong> a warm finish that many people find more stylish than silver.</li>
  <li><strong>Same performance:</strong> they move teeth the same way metal braces do.</li>
</ul>

