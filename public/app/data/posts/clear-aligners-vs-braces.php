<h2>How braces work</h2>
<p>Braces use small brackets bonded to the front of each tooth, connected by a thin archwire. At regular appointments, your orthodontist adjusts the wire to apply gentle, steady pressure that moves teeth into position.</p>
<p>Because braces are fixed in place, they work around the clock without you having to remember anything. Today's brackets are smaller and smoother than they used to be, and they come in metal, tooth-colored ceramic and even gold.</p>

<h2>How clear aligners work</h2>
<p>Clear aligners are a series of custom, removable plastic trays. Each set is shaped slightly differently from the last, and you switch to the next set on a schedule set by your orthodontist, usually every one to two weeks.</p>
<p>Aligners only work while they're in your mouth. They're typically worn <strong>20 to 22 hours a day</strong>, coming out just to eat, drink anything other than water, and brush.</p>

